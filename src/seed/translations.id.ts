/** Deep-copies `value`, replacing every string that has an Indonesian translation. */
export function translateToId<T>(value: T): T {
  if (typeof value === 'string') return (translationsId[value] ?? value) as T
  if (Array.isArray(value)) return value.map(translateToId) as T
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, translateToId(v)])) as T
  }
  return value
}
